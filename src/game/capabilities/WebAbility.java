package game.capabilities;

/**
 * Identifies web traps and actors that are immune to them.
 *
 * @author Surya Muni Peragas 35651628
 * @version 1.0.0
 */
public enum WebAbility {

    /**
     * Identifies an item as a web trap.
     */
    WEB_TRAP,

    /**
     * Prevents an actor from being bound by webs.
     */
    IMMUNE_TO_WEBS
}
