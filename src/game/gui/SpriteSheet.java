    private static BufferedImage minesBackdrop(int variant) {
        BufferedImage image = PixelArt.speckled(0x2c2738, 0x231f2d, 0x363044, 8, 600 + variant);
        int offset = variant % 2 == 0 ? 0 : 8;
        for (int x = 0; x < PixelArt.SIZE; x++) {
            PixelArt.plot(image, x, 7, 0xff1c1824);
            PixelArt.plot(image, x, 15, 0xff1c1824);
            PixelArt.plot(image, x, 0, 0xff3d374d);
            PixelArt.plot(image, x, 8, 0xff3d374d);
        }
        for (int y = 0; y < 8; y++) {
            PixelArt.plot(image, (4 + offset) % 16, y, 0xff1c1824);
            PixelArt.plot(image, (12 + offset) % 16, y + 8, 0xff1c1824);
        }
        return image;
    }

    private static BufferedImage furrows(int base, int dark, int light, long seed) {
        BufferedImage image = PixelArt.speckled(base, dark, light, 6, seed);
        for (int y = 0; y < PixelArt.SIZE; y++) {
            for (int x = 0; x < PixelArt.SIZE; x++) {
                if (y % 4 == 2) {
                    image.setRGB(x, y, 0xff000000 | dark);
                } else if (y % 4 == 3 && (x + y) % 5 != 0) {
                    image.setRGB(x, y, 0xff000000 | light);
                }
            }
        }
        return image;
    }

    private static void sparkle(BufferedImage image, long seed, int count, int colorA, int colorB) {
        Random random = new Random(seed);
        for (int index = 0; index < count; index++) {
            PixelArt.plot(image, random.nextInt(PixelArt.SIZE), random.nextInt(PixelArt.SIZE),
                    index % 2 == 0 ? colorA : colorB);
        }
    }

    private static double ellipse(int x, int y, double radiusX, double radiusY) {
        double dx = (x - 7.5) / radiusX;
        double dy = (y - 8.0) / radiusY;
        return dx * dx + dy * dy;
    }

    private static BufferedImage puddle() {
        BufferedImage image = PixelArt.blank();
        for (int y = 0; y < PixelArt.SIZE; y++) {
            for (int x = 0; x < PixelArt.SIZE; x++) {
                double distance = ellipse(x, y, 7.6, 6.2);
                if (distance < 0.72) {
                    image.setRGB(x, y, 0xff4aa3ee);
                } else if (distance < 1.0) {
                    image.setRGB(x, y, 0xff2b62b8);
                }
            }
        }
        for (int[] glint : new int[][] {{4, 5}, {5, 5}, {6, 5}, {4, 6}, {9, 10}, {10, 10}, {11, 9}, {8, 7}}) {
            image.setRGB(glint[0], glint[1], 0xff9fdcff);
        }
        return image;
    }

