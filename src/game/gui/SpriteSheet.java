    private static BufferedImage circle() {
        BufferedImage image = PixelArt.blank();
        for (int y = 0; y < PixelArt.SIZE; y++) {
            for (int x = 0; x < PixelArt.SIZE; x++) {
                double distance = ellipse(x, y, 7.4, 7.4);
                if (distance > 0.70 && distance < 1.0) {
                    image.setRGB(x, y, 0xffa060d0);
                } else if (distance > 0.52 && distance <= 0.70) {
                    image.setRGB(x, y, 0xff5b3a8c);
                } else if (distance <= 0.52) {
                    image.setRGB(x, y, 0x663b2a66);
                }
            }
        }
        for (int[] rune : new int[][] {{7, 1}, {8, 1}, {7, 14}, {8, 14}, {1, 7}, {1, 8}, {14, 7}, {14, 8}}) {
            image.setRGB(rune[0], rune[1], 0xff6ff0e0);
        }
        for (int[] star : new int[][] {{7, 5}, {8, 5}, {5, 8}, {10, 8}, {7, 11}, {8, 11}, {7, 8}, {8, 8}}) {
            image.setRGB(star[0], star[1], 0xff9fdcff);
        }
        return image;
    }

    private static BufferedImage web() {
        BufferedImage image = PixelArt.blank();
        int strand = 0xeef2f6fb;
        for (int index = 1; index < 15; index++) {
            PixelArt.plot(image, index, index, strand);
            PixelArt.plot(image, 15 - index, index, strand);
            PixelArt.plot(image, index, 8, strand);
            PixelArt.plot(image, 8, index, strand);
        }
        for (int ring : new int[] {3, 6}) {
            for (int step = 0; step <= ring; step++) {
                PixelArt.plot(image, 8 - ring + step, 8 - step, strand);
                PixelArt.plot(image, 8 + step, 8 - ring + step, strand);
                PixelArt.plot(image, 8 + ring - step, 8 + step, strand);
                PixelArt.plot(image, 8 - step, 8 + ring - step, strand);
            }
        }
        return image;
    }

    private static BufferedImage field(int rgb, long seed) {
        BufferedImage image = PixelArt.blank();
        for (int y = 0; y < PixelArt.SIZE; y++) {
            for (int x = 0; x < PixelArt.SIZE; x++) {
                double distance = ellipse(x, y, 8.2, 8.2);
                if (distance < 1.0) {
                    int alpha = (int) (40 + 70 * (1.0 - distance));
                    image.setRGB(x, y, (alpha << 24) | rgb);
                }
            }
        }
        Random random = new Random(seed);
        for (int index = 0; index < 5; index++) {
            int x = 3 + random.nextInt(10);
            int y = 3 + random.nextInt(10);
            PixelArt.plot(image, x, y, 0xffffffff);
            PixelArt.plot(image, x - 1, y, 0xff000000 | rgb);
            PixelArt.plot(image, x + 1, y, 0xff000000 | rgb);
            PixelArt.plot(image, x, y - 1, 0xff000000 | rgb);
            PixelArt.plot(image, x, y + 1, 0xff000000 | rgb);
        }
        return image;
    }
