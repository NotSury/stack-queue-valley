    private static BufferedImage farmFloor(int variant) {
        BufferedImage image = PixelArt.speckled(0xcfa46e, 0xb88c58, 0xddb884, 9, 100 + variant);
        Random random = new Random(200 + variant);
        int tufts = variant < 2 ? 0 : 1;
        for (int index = 0; index < tufts; index++) {
            int x = 2 + random.nextInt(11);
            int y = 3 + random.nextInt(10);
            PixelArt.plot(image, x, y, 0xff5ea83f);
            PixelArt.plot(image, x + 1, y - 1, 0xff7cc452);
            PixelArt.plot(image, x + 2, y, 0xff5ea83f);
            PixelArt.plot(image, x + 1, y, 0xff4c8f35);
        }
        return image;
    }

